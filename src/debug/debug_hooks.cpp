/**
 *  Prints an string to the debug handler.
 *
 *  @author: CCHyper
 */
static void __cdecl Debug_Print(const char *fmt, ...)
{
    va_list args;
    va_start(args, fmt);

    std::string tmp = fmt;

    char buffer[4096];
    vsprintf(buffer, tmp.c_str(), args);

    /**
     *  Re-escape any % signs.
     */
    Vinifera_Escape_Percent_Sign(buffer, sizeof(buffer));

    DEBUG_GAME(buffer);

    va_end(args);
}


